using System.Linq;
using Libraries.DNV.Editor.CodeGeneration;
using Libraries.DNV.Logging;
using UnityEditor;
using UnityEngine;

namespace Libraries.DNV.Editor
{
    /// <summary>
    /// Project Settings page ("Project/Logger"): Enabled toggle, colors of library categories,
    /// and the game's own categories, which are generated into GameLogCategories.
    /// </summary>
    public static class LogSettingsProvider
    {
        private static string _newCategoryName = string.Empty;

        [SettingsProvider]
        public static SettingsProvider CreateLogSettingsProvider()
        {
            return new SettingsProvider("Project/Logger", SettingsScope.Project)
            {
                guiHandler = searchContext => DrawGui(),
                keywords = new[] { "log", "logger", "logging", "color", "category" }
            };
        }

        private static void DrawGui()
        {
            var settings = LoggerSettingsBootstrap.EnsureAsset();

            EditorGUI.BeginChangeCheck();

            var enabled = EditorGUILayout.Toggle("Enabled", settings.Enabled);
            DrawLibraryCategories(settings);
            DrawGameCategories(settings);

            if (!EditorGUI.EndChangeCheck())
                return;

            settings.SetEnabled(enabled);
            settings.InvalidateColorCache();
            Save(settings);
        }

        private static void DrawLibraryCategories(LoggerSettings settings)
        {
            EditorGUILayout.Space();
            EditorGUILayout.LabelField("Library Categories", EditorStyles.boldLabel);

            using (new EditorGUI.IndentLevelScope())
            {
                foreach (var entry in settings.Categories.Where(entry => !entry.IsGameCategory))
                {
                    DrawColor(entry);
                }
            }
        }

        private static void DrawGameCategories(LoggerSettings settings)
        {
            EditorGUILayout.Space();
            EditorGUILayout.LabelField("Game Categories", EditorStyles.boldLabel);

            using (new EditorGUI.IndentLevelScope())
            {
                foreach (var entry in settings.GameCategories.ToArray())
                {
                    EditorGUILayout.BeginHorizontal();
                    entry.SetName(EditorGUILayout.DelayedTextField(entry.Name));
                    entry.SetColor(EditorGUILayout.ColorField(GUIContent.none, entry.Color, true, false, false));

                    if (GUILayout.Button("X", GUILayout.Width(24f)))
                    {
                        settings.RemoveGameCategory(entry.Id);
                        GUI.changed = true;
                    }

                    EditorGUILayout.EndHorizontal();
                }

                EditorGUILayout.BeginHorizontal();
                _newCategoryName = EditorGUILayout.TextField(_newCategoryName);

                if (GUILayout.Button("Add", GUILayout.Width(60f)) && !string.IsNullOrWhiteSpace(_newCategoryName))
                {
                    settings.AddGameCategory(_newCategoryName.Trim());
                    _newCategoryName = string.Empty;
                    GUI.changed = true;
                }

                EditorGUILayout.EndHorizontal();
            }

            if (GUILayout.Button("Generate GameLogCategories"))
            {
                Save(settings);
                LogCategoriesGenerator.Generate(settings);
            }

            EditorGUILayout.HelpBox(
                "Game categories become GameLogCategories.Xxx in Assets/LibraryDependence/AutoGenerated after Generate.",
                MessageType.Info);
        }

        private static void DrawColor(LogCategoryColor entry)
        {
            var label = ObjectNames.NicifyVariableName(entry.Name ?? entry.Id.ToString());
            entry.SetColor(EditorGUILayout.ColorField(new GUIContent(label), entry.Color, true, false, false));
        }

        private static void Save(LoggerSettings settings)
        {
            EditorUtility.SetDirty(settings);
            AssetDatabase.SaveAssets();
        }
    }
}
