using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using Libraries.DNV.Core;
using Libraries.DNV.Logging;

namespace Libraries.DNV.Editor.CodeGeneration
{
    /// <summary>
    /// The only place that knows where generated code goes, its namespace and how ids become identifiers.
    /// </summary>
    public static class GeneratedCodeWriter
    {
        public const string Namespace = "AutoGenerated";

        public static void WriteConstants(string className, IEnumerable<GeneratedConstant> constants)
        {
            var members = BuildMembers(className, constants,
                (identifier, constant) => $"public const string {identifier} = \"{Escape(constant.Value)}\";");

            WriteMembers(className, members);
        }

        /// <summary>
        /// Writes a static class whose members are already formatted declarations (e.g. readonly fields).
        /// </summary>
        public static void WriteMembers(string className, IEnumerable<string> members, params string[] usings)
        {
            var path = ProjectPath.Generated.Root + className + ".cs";

            WriteIfChanged(path, BuildClass(className, members, usings));
        }

        /// <summary>
        /// Turns keys into unique identifiers, warning about and skipping the ones that collide or are empty.
        /// </summary>
        public static IEnumerable<string> BuildMembers<TItem>(string className, IEnumerable<TItem> items,
            Func<string, TItem, string> declaration) where TItem : IGeneratedKey
        {
            var usedIdentifiers = new HashSet<string>();

            foreach(var item in items)
            {
                var identifier = ToIdentifier(item.Key);

                if(string.IsNullOrEmpty(identifier))
                {
                    Log.Warning(LogCategory.Editor, $"[{className}] '{item.Key}' cannot be turned into an identifier, skipped.");
                    continue;
                }

                if(usedIdentifiers.Add(identifier) == false)
                {
                    Log.Warning(LogCategory.Editor, $"[{className}] '{item.Key}' collides with another id as '{identifier}', skipped.");
                    continue;
                }

                yield return declaration(identifier, item);
            }
        }

        private static string BuildClass(string className, IEnumerable<string> members, IEnumerable<string> usings)
        {
            var builder = new StringBuilder();

            builder.AppendLine($"// Auto-generated by {nameof(GeneratedCodeWriter)}. Do not edit manually.");
            builder.AppendLine();

            var hasUsings = false;
            foreach(var usingNamespace in usings)
            {
                builder.AppendLine($"using {usingNamespace};");
                hasUsings = true;
            }

            if(hasUsings)
            {
                builder.AppendLine();
            }

            builder.AppendLine($"namespace {Namespace}");
            builder.AppendLine("{");
            builder.AppendLine($"    public static class {className}");
            builder.AppendLine("    {");

            foreach(var member in members)
            {
                builder.AppendLine($"        {member}");
            }

            builder.AppendLine("    }");
            builder.AppendLine("}");

            return builder.ToString();
        }

        private static void WriteIfChanged(string path, string code)
        {
            if(File.Exists(path) && File.ReadAllText(path) == code)
            {
                return;
            }

            Directory.CreateDirectory(Path.GetDirectoryName(path));
            File.WriteAllText(path, code);

            Log.Info(LogCategory.Editor, $"[{nameof(GeneratedCodeWriter)}] Generated {path}");
        }

        /// <summary>
        /// Keeps the original casing so "CubeEffect" stays "CubeEffect" and "Man-Kick-1" becomes "ManKick1".
        /// </summary>
        private static string ToIdentifier(string input)
        {
            if(string.IsNullOrEmpty(input))
            {
                return string.Empty;
            }

            var cleaned = Regex.Replace(input, @"[^a-zA-Z0-9_\s]", "");
            var words = cleaned.Split(new[] { ' ', '_', '\t' }, StringSplitOptions.RemoveEmptyEntries);

            if(words.Length == 0)
            {
                return string.Empty;
            }

            var builder = new StringBuilder();

            foreach(var word in words)
            {
                builder.Append(char.ToUpperInvariant(word[0])).Append(word.Substring(1));
            }

            var result = builder.ToString();

            return char.IsDigit(result[0]) ? "_" + result : result;
        }

        private static string Escape(string value)
        {
            return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
        }
    }
}
